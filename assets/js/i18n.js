(function () {
  const STORE = "c2c_lang";
  function detect() {
    // 1) Paramètre URL (?lang=en) — permet aux flyers EN de forcer l'anglais
    //    à l'atterrissage sans rompre la persistance pour les visites suivantes.
    try {
      const q = new URLSearchParams(location.search).get("lang");
      if (q && I18N[q.toLowerCase()]) return q.toLowerCase();
    } catch (_) { /* URL API indisponible → on ignore */ }
    // 2) Choix mémorisé lors d'une visite précédente
    const saved = localStorage.getItem(STORE);
    if (saved && I18N[saved]) return saved;
    // 3) Repli sur la langue du navigateur
    const nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : "fr";
  }

  let lang = detect();

  function apply(l) {
    lang = I18N[l] ? l : "fr";
    localStorage.setItem(STORE, lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (I18N[lang][key] != null) el.textContent = I18N[lang][key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (I18N[lang][key] != null) el.innerHTML = I18N[lang][key];
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      const key = el.getAttribute("data-i18n-ph");
      if (I18N[lang][key] != null) el.setAttribute("placeholder", I18N[lang][key]);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const key = el.getAttribute("data-i18n-alt");
      if (I18N[lang][key] != null) el.setAttribute("alt", I18N[lang][key]);
    });

    document.querySelectorAll(".lang-switch button").forEach((b) => {
      b.classList.toggle("active", b.dataset.lang === lang);
    });

    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  // Expose
  window.C2C_I18N = {
    t: (key) => (I18N[lang] && I18N[lang][key]) || (I18N.fr[key] || key),
    get lang() { return lang; },
    set: apply,
  };

  document.addEventListener("DOMContentLoaded", () => {
    apply(lang);
    document.querySelectorAll(".lang-switch button").forEach((b) => {
      b.addEventListener("click", () => apply(b.dataset.lang));
    });
  });
})();
